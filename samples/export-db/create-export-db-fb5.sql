   não gera para estes tipos: eles são cobertos só pela ida e volta (ADR 0008). Mudar este arquivo não exige
   regenerar a Referência. */

SET TERM ^ ;

/* Sequences com START WITH e INCREMENT; SET GENERATOR deixa o valor atual longe do inicial. */
CREATE SEQUENCE SEQ_PASSO START WITH 100 INCREMENT BY 5^
CREATE SEQUENCE SEQ_DESCENDO START WITH 50 INCREMENT BY -5^
CREATE SEQUENCE SEQ_INICIO START WITH 1000^
SET GENERATOR SEQ_PASSO TO 120^

/* Collations: os três atributos e a especificação de ICU. */
CREATE COLLATION UNICODE_NUMERICO FOR UTF8 FROM UNICODE PAD SPACE CASE INSENSITIVE ACCENT SENSITIVE
    'NUMERIC-SORT=1'^
CREATE COLLATION UNICODE_SEM_ACENTO FOR UTF8 FROM UNICODE NO PAD CASE INSENSITIVE ACCENT INSENSITIVE^
CREATE COLLATION PTBR_SEM_PAD FOR WIN1252 FROM WIN_PTBR NO PAD CASE SENSITIVE ACCENT SENSITIVE^

DECLARE FILTER FILTRO_TEXTO INPUT_TYPE 1 OUTPUT_TYPE -4 ENTRY_POINT 'filtro_texto' MODULE_NAME 'filtros'^

/* UDFs (functions legadas): retorno por valor, por parâmetro, CSTRING com FREE_IT, BY DESCRIPTOR, BLOB e charset. */
DECLARE EXTERNAL FUNCTION UDF_TEXTO INTEGER, VARCHAR(10)
    RETURNS CSTRING(20) FREE_IT ENTRY_POINT 'udf_texto' MODULE_NAME 'udfs'^
DECLARE EXTERNAL FUNCTION UDF_PARAMETRO INTEGER BY DESCRIPTOR, DOUBLE PRECISION
    RETURNS PARAMETER 2 ENTRY_POINT 'udf_parametro' MODULE_NAME 'udfs'^
DECLARE EXTERNAL FUNCTION UDF_VALOR CSTRING(10), BLOB
    RETURNS INTEGER BY VALUE ENTRY_POINT 'udf_valor' MODULE_NAME 'udfs'^
DECLARE EXTERNAL FUNCTION UDF_ZERO RETURNS DOUBLE PRECISION ENTRY_POINT 'udf_zero' MODULE_NAME 'udfs'^
DECLARE EXTERNAL FUNCTION UDF_MATRIZ INTEGER BY SCALAR_ARRAY
    RETURNS INTEGER BY VALUE ENTRY_POINT 'udf_matriz' MODULE_NAME 'udfs'^
DECLARE EXTERNAL FUNCTION UDF_DATA TIMESTAMP, DATE
    RETURNS VARCHAR(5) CHARACTER SET WIN1252 FREE_IT ENTRY_POINT 'udf_data' MODULE_NAME 'udfs'^

CREATE ROLE ADMIN_USUARIOS SET SYSTEM PRIVILEGES TO USER_MANAGEMENT, MONITOR_ANY_ATTACHMENT^

/* Mappings locais: plugin, qualquer plugin, outro mapping, banco, grupo e role. */
CREATE MAPPING MAP_SRP USING PLUGIN SRP FROM ANY USER TO USER^
CREATE MAPPING MAP_PAPEL USING PLUGIN SRP FROM USER 'Sasha' TO ROLE GERENTE^
CREATE MAPPING MAP_QUALQUER USING ANY PLUGIN IN OUTRO FROM ANY GROUP TO USER^
CREATE MAPPING MAP_ENCADEADO USING MAPPING FROM ANY USER TO ROLE VENDEDOR^

/* Triggers de tabela com os três eventos e SQL SECURITY. */
CREATE TRIGGER TR_CATEGORIA_AIUD FOR CATEGORIA
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 40
AS
BEGIN
  EXIT;
END^

CREATE TRIGGER TR_CATEGORIA_BD FOR CATEGORIA
ACTIVE BEFORE DELETE OR INSERT POSITION 30 SQL SECURITY DEFINER
AS
BEGIN
  EXIT;
END^

/* Triggers de banco e DDL. Os de DDL ficam inativos para não disparar nas outras criações do script. */
CREATE TRIGGER TR_BANCO_CONECTA ACTIVE ON CONNECT POSITION 0
AS
  DECLARE VARIABLE V INTEGER;
BEGIN
  V = 1;
END^

CREATE TRIGGER TR_BANCO_COMMIT INACTIVE ON TRANSACTION COMMIT POSITION 5
AS
BEGIN
  EXIT;
END^

CREATE TRIGGER TR_DDL_QUALQUER INACTIVE BEFORE ANY DDL STATEMENT POSITION 0
AS
BEGIN
  EXIT;
END^

CREATE TRIGGER TR_DDL_TABELAS INACTIVE AFTER CREATE TABLE OR ALTER TABLE OR DROP TABLE POSITION 5
AS
BEGIN
  EXIT;
END^

SET TERM ; ^

