CREATE TABLE PRODUTO (
  ID           D_ID,
  ID_CATEGORIA INTEGER,
  DESCRICAO    D_NOME NOT NULL,
  PRECO        D_DINHEIRO,
  CUSTO        NUMERIC(15,4) DEFAULT 0,
  MARGEM       COMPUTED BY (CASE WHEN CUSTO > 0 THEN (PRECO - CUSTO) / CUSTO * 100 ELSE NULL END),
