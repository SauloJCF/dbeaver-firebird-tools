/* ---------- Views (V_PEDIDO_RESUMO depende de V_PEDIDO_TOTAL: ordem topológica) ---------- */
CREATE VIEW V_CLIENTE_ATIVO (ID, NOME, CIDADE) AS
  SELECT ID, NOME, CIDADE FROM CLIENTE WHERE SITUACAO = 'ATIVO';

CREATE VIEW V_PEDIDO_TOTAL (ID_PEDIDO, TOTAL) AS
  SELECT ID_PEDIDO, SUM(QUANTIDADE * PRECO_UNIT) FROM ITEM_PEDIDO GROUP BY ID_PEDIDO;

CREATE VIEW V_PEDIDO_RESUMO (ID_PEDIDO, NOME_CLIENTE, TOTAL_ITENS) AS
  SELECT P.ID, C.NOME, T.TOTAL
    FROM PEDIDO P
    JOIN CLIENTE C ON C.ID = P.ID_CLIENTE
    JOIN V_PEDIDO_TOTAL T ON T.ID_PEDIDO = P.ID;

