ALTER PROCEDURE SP_TOTAL_PEDIDO (ID_PEDIDO INTEGER)
RETURNS (TOTAL NUMERIC(15,2))
AS
BEGIN
  SELECT COALESCE(SUM(QUANTIDADE * PRECO_UNIT), 0)
    FROM ITEM_PEDIDO
   WHERE ID_PEDIDO = :ID_PEDIDO
    INTO :TOTAL;
  SUSPEND;
END^

ALTER PROCEDURE SP_LISTA_CLIENTES (CIDADE_FILTRO VARCHAR(60))
RETURNS (ID INTEGER, NOME VARCHAR(80), CIDADE VARCHAR(60))
AS
BEGIN
  FOR SELECT ID, NOME, CIDADE
        FROM CLIENTE
       WHERE CIDADE = :CIDADE_FILTRO OR :CIDADE_FILTRO IS NULL
       ORDER BY NOME
        INTO :ID, :NOME, :CIDADE
  DO
    SUSPEND;
END^

ALTER PROCEDURE SP_FECHAR_PEDIDO (ID_PEDIDO INTEGER)
AS
  DECLARE VARIABLE V_TOTAL NUMERIC(15,2);
  DECLARE VARIABLE V_STATUS VARCHAR(10);
BEGIN
  SELECT STATUS FROM PEDIDO WHERE ID = :ID_PEDIDO INTO :V_STATUS;
  IF (V_STATUS = 'FECHADO') THEN
    EXCEPTION E_PEDIDO_FECHADO;
  SELECT TOTAL FROM SP_TOTAL_PEDIDO(:ID_PEDIDO) INTO :V_TOTAL;
  UPDATE PEDIDO SET STATUS = 'FECHADO', TOTAL = :V_TOTAL WHERE ID = :ID_PEDIDO;
END^

