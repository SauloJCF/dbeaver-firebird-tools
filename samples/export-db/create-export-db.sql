BEGIN
  SELECT ESTOQUE FROM PRODUTO WHERE ID = NEW.ID_PRODUTO INTO :V_ESTOQUE;
  IF (V_ESTOQUE < NEW.QUANTIDADE) THEN
    EXCEPTION E_ESTOQUE_INSUFICIENTE;
END^

CREATE TRIGGER TR_PEDIDO_BIU_CLIENTE FOR PEDIDO
ACTIVE BEFORE INSERT OR UPDATE POSITION 10
AS
  DECLARE VARIABLE V_SITUACAO VARCHAR(10);
BEGIN
  SELECT SITUACAO FROM CLIENTE WHERE ID = NEW.ID_CLIENTE INTO :V_SITUACAO;
  IF (V_SITUACAO = 'BLOQUEADO') THEN
    EXCEPTION E_CLIENTE_BLOQUEADO;
END^

CREATE TRIGGER TR_PEDIDO_AU_LOG FOR PEDIDO
ACTIVE AFTER UPDATE POSITION 20
AS
BEGIN
  IF (OLD.STATUS <> NEW.STATUS) THEN
    INSERT INTO LOG (ID, TABELA, OPERACAO, DETALHE)
    VALUES (GEN_ID(GEN_LOG, 1), 'PEDIDO', 'U',
            'Status ' || OLD.STATUS || ' -> ' || NEW.STATUS);
END^

CREATE TRIGGER TR_CLIENTE_AD_LOG FOR CLIENTE
ACTIVE AFTER DELETE POSITION 20
AS
BEGIN
  INSERT INTO LOG (ID, TABELA, OPERACAO, DETALHE)
  VALUES (GEN_ID(GEN_LOG, 1), 'CLIENTE', 'D', 'Cliente ' || OLD.NOME);
END^

CREATE TRIGGER TR_LOG_BI_INATIVA FOR LOG
INACTIVE BEFORE INSERT POSITION 99
AS
BEGIN
  NEW.DETALHE = COALESCE(NEW.DETALHE, '');
END^

