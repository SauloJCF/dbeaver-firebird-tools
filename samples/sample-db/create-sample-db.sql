CREATE TABLE CLIENTE (
  ID         INTEGER NOT NULL PRIMARY KEY,
  NOME       VARCHAR(80) NOT NULL,
  CIDADE     VARCHAR(60),
  LIMITE     NUMERIC(12,2) DEFAULT 1000 NOT NULL,
