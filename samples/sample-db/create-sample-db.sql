/* ---------- Triggers ---------- */
CREATE TRIGGER TRG_CLIENTE_BI FOR CLIENTE ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ID IS NULL) THEN NEW.ID = NEXT VALUE FOR GEN_CLIENTE;
  NEW.NOME = UPPER(TRIM(NEW.NOME));
END^

/* universal: cada evento segue um ramo (Trigger isolada, issue 19) */
CREATE TRIGGER TRG_CLIENTE_BIUD FOR CLIENTE ACTIVE BEFORE INSERT OR UPDATE OR DELETE POSITION 10 AS
  DECLARE VARIABLE V_EVENTO VARCHAR(10);
  DECLARE VARIABLE V_DETALHE VARCHAR(200);
BEGIN
  IF (INSERTING) THEN
  BEGIN
    V_EVENTO = 'INSERT';
    NEW.CIDADE = COALESCE(NEW.CIDADE, 'NAO INFORMADA');
    V_DETALHE = NEW.NOME;
  END
  ELSE IF (UPDATING) THEN
  BEGIN
    V_EVENTO = 'UPDATE';
    IF (NEW.LIMITE < OLD.LIMITE) THEN NEW.ATIVO = 0;
    V_DETALHE = OLD.LIMITE || ' -> ' || NEW.LIMITE;
  END
  ELSE
  BEGIN
    V_EVENTO = 'DELETE';
    V_DETALHE = OLD.NOME;
  END
  INSERT INTO LOG_CLIENTE (EVENTO, ID_CLIENTE, DETALHE) VALUES (:V_EVENTO, COALESCE(NEW.ID, OLD.ID), :V_DETALHE);
END^

CREATE TRIGGER TRG_PRODUTO_BI FOR PRODUTO ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ID IS NULL) THEN NEW.ID = NEXT VALUE FOR GEN_PRODUTO;
END^

CREATE TRIGGER TRG_PEDIDO_BI FOR PEDIDO ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ID IS NULL) THEN NEW.ID = NEXT VALUE FOR GEN_PEDIDO;
END^

CREATE TRIGGER TRG_ITEM_PEDIDO_BI FOR ITEM_PEDIDO ACTIVE BEFORE INSERT POSITION 0 AS
  DECLARE VARIABLE V_STATUS VARCHAR(10);
BEGIN
  IF (NEW.ID IS NULL) THEN NEW.ID = NEXT VALUE FOR GEN_ITEM_PEDIDO;
  SELECT STATUS FROM PEDIDO WHERE ID = NEW.ID_PEDIDO INTO :V_STATUS;
  IF (V_STATUS = 'FECHADO') THEN EXCEPTION E_PEDIDO_FECHADO;
  IF (NEW.PRECO_UNIT IS NULL) THEN
    SELECT PRECO FROM PRODUTO WHERE ID = NEW.ID_PRODUTO INTO NEW.PRECO_UNIT;
END^

CREATE TRIGGER TRG_ITEM_PEDIDO_AI FOR ITEM_PEDIDO ACTIVE AFTER INSERT POSITION 0 AS
BEGIN
  UPDATE PRODUTO SET ESTOQUE = ESTOQUE - NEW.QUANTIDADE WHERE ID = NEW.ID_PRODUTO;
  UPDATE PEDIDO SET TOTAL = TOTAL + NEW.QUANTIDADE * NEW.PRECO_UNIT WHERE ID = NEW.ID_PEDIDO;
END^

CREATE TRIGGER TRG_PRODUTO_AU FOR PRODUTO ACTIVE AFTER UPDATE POSITION 0 AS
BEGIN
  IF (OLD.ESTOQUE <> NEW.ESTOQUE) THEN
    INSERT INTO LOG_ESTOQUE (ID, ID_PRODUTO, ANTES, DEPOIS)
    VALUES (NEXT VALUE FOR GEN_LOG_ESTOQUE, NEW.ID, OLD.ESTOQUE, NEW.ESTOQUE);
END^

/* ---------- Funcoes ---------- */
CREATE FUNCTION FN_FATORIAL (N INTEGER) RETURNS BIGINT AS
  DECLARE VARIABLE R BIGINT = 1;
  DECLARE VARIABLE I INTEGER = 2;
BEGIN
  WHILE (I <= N) DO
  BEGIN
    R = R * I;
    I = I + 1;
  END
  RETURN R;
END^

CREATE FUNCTION FN_DESCONTO (P_TOTAL NUMERIC(12,2)) RETURNS NUMERIC(12,2) AS
BEGIN
  IF (P_TOTAL >= 5000) THEN RETURN P_TOTAL * 0.10;
  ELSE IF (P_TOTAL >= 1000) THEN RETURN P_TOTAL * 0.05;
  RETURN 0;
END^

/* ---------- Procedures ---------- */
/* WHILE e variaveis */
CREATE PROCEDURE SP_FIBONACCI (N INTEGER) RETURNS (RESULTADO BIGINT) AS
  DECLARE VARIABLE A BIGINT = 0;
  DECLARE VARIABLE B BIGINT = 1;
  DECLARE VARIABLE T BIGINT;
  DECLARE VARIABLE I INTEGER = 0;
BEGIN
  WHILE (I < N) DO
  BEGIN
    T = A + B;
    A = B;
    B = T;
    I = I + 1;
  END
  RESULTADO = A;
  SUSPEND;
END^

/* selecionavel: FOR SELECT + SUSPEND */
CREATE PROCEDURE SP_PRODUTOS_BAIXO_ESTOQUE (MINIMO INTEGER)
  RETURNS (ID INTEGER, DESCRICAO VARCHAR(80), ESTOQUE INTEGER, FALTA INTEGER) AS
BEGIN
  FOR SELECT ID, DESCRICAO, ESTOQUE FROM PRODUTO WHERE ESTOQUE < :MINIMO ORDER BY ESTOQUE
      INTO :ID, :DESCRICAO, :ESTOQUE
  DO
  BEGIN
    FALTA = MINIMO - ESTOQUE;
    SUSPEND;
  END
END^

/* chama funcoes, usa EXIT */
CREATE PROCEDURE SP_RESUMO_PEDIDO (P_ID_PEDIDO INTEGER)
  RETURNS (CLIENTE VARCHAR(80), QTD_ITENS INTEGER, TOTAL NUMERIC(12,2), DESCONTO NUMERIC(12,2), A_PAGAR NUMERIC(12,2)) AS
  DECLARE VARIABLE V_ID_CLIENTE INTEGER;
BEGIN
  SELECT ID_CLIENTE, TOTAL FROM PEDIDO WHERE ID = :P_ID_PEDIDO INTO :V_ID_CLIENTE, :TOTAL;
  IF (V_ID_CLIENTE IS NULL) THEN
  BEGIN
    CLIENTE = '(pedido inexistente)';
    SUSPEND;
    EXIT;
  END
  SELECT NOME FROM CLIENTE WHERE ID = :V_ID_CLIENTE INTO :CLIENTE;
  SELECT COUNT(*) FROM ITEM_PEDIDO WHERE ID_PEDIDO = :P_ID_PEDIDO INTO :QTD_ITENS;
  DESCONTO = FN_DESCONTO(TOTAL);
  A_PAGAR = TOTAL - DESCONTO;
  SUSPEND;
END^

/* grava dados (dispara triggers) e levanta EXCEPTION */
CREATE PROCEDURE SP_ADICIONA_ITEM (P_ID_PEDIDO INTEGER, P_ID_PRODUTO INTEGER, P_QTD INTEGER)
  RETURNS (ID_ITEM INTEGER) AS
  DECLARE VARIABLE V_ESTOQUE INTEGER;
BEGIN
  SELECT ESTOQUE FROM PRODUTO WHERE ID = :P_ID_PRODUTO INTO :V_ESTOQUE;
  IF (V_ESTOQUE IS NULL OR V_ESTOQUE < P_QTD) THEN
    EXCEPTION E_ESTOQUE_INSUFICIENTE;
  ID_ITEM = NEXT VALUE FOR GEN_ITEM_PEDIDO;
  INSERT INTO ITEM_PEDIDO (ID, ID_PEDIDO, ID_PRODUTO, QUANTIDADE)
  VALUES (:ID_ITEM, :P_ID_PEDIDO, :P_ID_PRODUTO, :P_QTD);
END^

/* chamada aninhada em loop, com tratamento WHEN */
CREATE PROCEDURE SP_PEDIDO_RAPIDO (P_ID_CLIENTE INTEGER, P_QTD_POR_PRODUTO INTEGER)
  RETURNS (ID_PEDIDO INTEGER, ITENS_OK INTEGER, ITENS_FALHA INTEGER) AS
  DECLARE VARIABLE V_PROD INTEGER;
  DECLARE VARIABLE V_ITEM INTEGER;
BEGIN
  ITENS_OK = 0;
  ITENS_FALHA = 0;
  ID_PEDIDO = NEXT VALUE FOR GEN_PEDIDO;
  INSERT INTO PEDIDO (ID, ID_CLIENTE) VALUES (:ID_PEDIDO, :P_ID_CLIENTE);
  FOR SELECT ID FROM PRODUTO ORDER BY ID INTO :V_PROD DO
  BEGIN
    BEGIN
      EXECUTE PROCEDURE SP_ADICIONA_ITEM(:ID_PEDIDO, :V_PROD, :P_QTD_POR_PRODUTO)
        RETURNING_VALUES :V_ITEM;
      ITENS_OK = ITENS_OK + 1;
      WHEN EXCEPTION E_ESTOQUE_INSUFICIENTE DO
        ITENS_FALHA = ITENS_FALHA + 1;
    END
  END
  SUSPEND;
END^

/* executavel com WHILE, IF e SELECT ... INTO: breakpoints, step e edicao de variavel */
CREATE PROCEDURE SP_SOMA_ESTOQUE (P_LIMITE INTEGER)
  RETURNS (TOTAL INTEGER, ACIMA INTEGER) AS
  DECLARE VARIABLE V_ID INTEGER = 0;
  DECLARE VARIABLE V_ESTOQUE INTEGER;
BEGIN
  TOTAL = 0;
  ACIMA = 0;
  WHILE (V_ID < 6) DO
  BEGIN
    V_ID = V_ID + 1;
    SELECT ESTOQUE FROM PRODUTO WHERE ID = :V_ID INTO :V_ESTOQUE;
    IF (V_ESTOQUE > P_LIMITE) THEN
      ACIMA = ACIMA + 1;
    TOTAL = TOTAL + V_ESTOQUE;
  END
END^

/* executavel que grava e continua: watches que veem o que a sessao alterou */
CREATE PROCEDURE SP_REPOE_ESTOQUE (P_ID_PRODUTO INTEGER, P_QTD INTEGER)
  RETURNS (ESTOQUE_ANTES INTEGER, ESTOQUE_DEPOIS INTEGER) AS
BEGIN
  SELECT ESTOQUE FROM PRODUTO WHERE ID = :P_ID_PRODUTO INTO :ESTOQUE_ANTES;
  UPDATE PRODUTO SET ESTOQUE = ESTOQUE + :P_QTD WHERE ID = :P_ID_PRODUTO;
  SELECT ESTOQUE FROM PRODUTO WHERE ID = :P_ID_PRODUTO INTO :ESTOQUE_DEPOIS;
END^

CREATE PROCEDURE SP_FECHA_PEDIDO (P_ID_PEDIDO INTEGER) AS
  DECLARE VARIABLE V_STATUS VARCHAR(10);
BEGIN
  SELECT STATUS FROM PEDIDO WHERE ID = :P_ID_PEDIDO INTO :V_STATUS;
  IF (V_STATUS = 'FECHADO') THEN EXCEPTION E_PEDIDO_FECHADO;
  UPDATE PEDIDO SET STATUS = 'FECHADO' WHERE ID = :P_ID_PEDIDO;
END^

/* cadeia de chamadas para step into e step return: SP_FATURA_PEDIDO -> SP_TOTAL_PEDIDO -> SP_VALOR_ITEM */
CREATE PROCEDURE SP_VALOR_ITEM (P_QTD INTEGER, P_PRECO NUMERIC(12,2))
  RETURNS (VALOR NUMERIC(12,2)) AS
BEGIN
  VALOR = P_QTD * P_PRECO;
  IF (P_QTD >= 5) THEN
    VALOR = VALOR * 0.95;
END^

CREATE PROCEDURE SP_TOTAL_PEDIDO (P_ID_PEDIDO INTEGER)
  RETURNS (TOTAL NUMERIC(12,2), ITENS INTEGER) AS
  DECLARE VARIABLE V_QTD INTEGER;
  DECLARE VARIABLE V_PRECO NUMERIC(12,2);
  DECLARE VARIABLE V_VALOR NUMERIC(12,2);
BEGIN
  TOTAL = 0;
  ITENS = 0;
  FOR SELECT QUANTIDADE, PRECO_UNIT FROM ITEM_PEDIDO WHERE ID_PEDIDO = :P_ID_PEDIDO ORDER BY ID
      INTO :V_QTD, :V_PRECO
  DO
  BEGIN
    EXECUTE PROCEDURE SP_VALOR_ITEM(:V_QTD, :V_PRECO) RETURNING_VALUES :V_VALOR;
    TOTAL = TOTAL + V_VALOR;
    ITENS = ITENS + 1;
  END
END^

/* step into em procedure, function e sub-rotina; FN_DESCONTO dentro do INSERT ... SELECT e executada no servidor */
CREATE PROCEDURE SP_FATURA_PEDIDO (P_ID_PEDIDO INTEGER)
  RETURNS (TOTAL NUMERIC(12,2), ITENS INTEGER, DESCONTO NUMERIC(12,2), A_PAGAR NUMERIC(12,2),
           HISTORICOS INTEGER) AS
  DECLARE FUNCTION ARREDONDA (V NUMERIC(12,2)) RETURNS NUMERIC(12,2)
  AS
    DECLARE R NUMERIC(12,2);
  BEGIN
    R = ROUND(V, 0);
    RETURN R;
  END
BEGIN
  EXECUTE PROCEDURE SP_TOTAL_PEDIDO(:P_ID_PEDIDO) RETURNING_VALUES :TOTAL, :ITENS;
  DESCONTO = FN_DESCONTO(TOTAL);
  A_PAGAR = ARREDONDA(TOTAL - DESCONTO);
  INSERT INTO HISTORICO_PEDIDO (ID_PEDIDO, TOTAL, DESCONTO)
    SELECT :P_ID_PEDIDO, :TOTAL, FN_DESCONTO(:TOTAL) FROM RDB$DATABASE;
  SELECT COUNT(*) FROM HISTORICO_PEDIDO WHERE ID_PEDIDO = :P_ID_PEDIDO INTO :HISTORICOS;
END^

/* issue 24 (teste manual): tipos nativos com DataTypeCompatibility = 2.5 no servidor. Depure com P_ATIVO = TRUE:
   V_ATIVO deve aparecer como TRUE (sem espaco no fim), R_VALOR como 1000 (sem .0), o IF e a condicao do FOR SELECT
   nao podem dar "invalid usage of boolean expression", e com P_LANCA = TRUE a mensagem deve ser "Ativo: TRUE". */
CREATE PROCEDURE SP_TIPOS_NATIVOS (P_ATIVO BOOLEAN, P_LANCA BOOLEAN)
  RETURNS (R_ATIVO BOOLEAN, R_VALOR DECFLOAT(16), R_MSG VARCHAR(40)) AS
  DECLARE V_ATIVO BOOLEAN;
  DECLARE V_COLUNA BOOLEAN;
BEGIN
  V_ATIVO = P_ATIVO;
  R_ATIVO = V_ATIVO;
  R_VALOR = 1000;
  IF (V_ATIVO) THEN
    R_MSG = 'ativo';
  ELSE
    R_MSG = 'inativo';
  FOR SELECT TRUE FROM RDB$DATABASE INTO :V_COLUNA
  DO
  BEGIN
    IF (V_COLUNA) THEN
      R_MSG = R_MSG || ' / coluna ativa';
  END
  SUSPEND;
  IF (P_LANCA) THEN
    EXCEPTION E_COM_BOOLEAN USING (V_ATIVO);
END^

/* ---------- Package ---------- */
/* depurada pelo console do corpo (PSQL Debug > Abrir Package): selecionavel, function e function privada */
CREATE PACKAGE PKG_ESTOQUE AS
BEGIN
  PROCEDURE REPOSICAO (P_MINIMO INTEGER) RETURNS (ID INTEGER, DESCRICAO VARCHAR(80), PEDIR INTEGER);
  FUNCTION VALOR_ESTOQUE (P_ID_PRODUTO INTEGER) RETURNS NUMERIC(12,2);
END^

CREATE PACKAGE BODY PKG_ESTOQUE AS
BEGIN
  FUNCTION LOTE (P_QTD INTEGER) RETURNS INTEGER
  AS
  BEGIN
    RETURN (P_QTD + 9) / 10 * 10;
  END

  PROCEDURE REPOSICAO (P_MINIMO INTEGER) RETURNS (ID INTEGER, DESCRICAO VARCHAR(80), PEDIR INTEGER)
  AS
    DECLARE V_ESTOQUE INTEGER;
  BEGIN
    FOR SELECT ID, DESCRICAO, ESTOQUE FROM PRODUTO WHERE ESTOQUE < :P_MINIMO ORDER BY ID
        INTO :ID, :DESCRICAO, :V_ESTOQUE
    DO
    BEGIN
      PEDIR = LOTE(P_MINIMO - V_ESTOQUE);
      SUSPEND;
    END
  END

  FUNCTION VALOR_ESTOQUE (P_ID_PRODUTO INTEGER) RETURNS NUMERIC(12,2)
  AS
    DECLARE V_VALOR NUMERIC(12,2);
  BEGIN
    SELECT PRECO * ESTOQUE FROM PRODUTO WHERE ID = :P_ID_PRODUTO INTO :V_VALOR;
    RETURN V_VALOR;
  END
END^

